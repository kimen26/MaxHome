-- Liste « À faire » d'un voyage (brief fiche-voyage-v3.md, lot 1). Additif, idempotent.
-- Cochable : `fait_le` / `fait_par` renseignés = fait. Même RLS que les autres tables voyage.

create table if not exists voyage_todos (
  id         bigint generated by default as identity primary key,
  voyage_id  bigint not null references voyages(id) on delete cascade,
  texte      text not null,
  detail     text,
  lien       text,
  ordre      int not null default 0,
  fait_le    timestamptz,
  fait_par   text,
  cree_par   text,
  cree_le    timestamptz not null default now()
);
create index if not exists voyage_todos_voyage on voyage_todos (voyage_id);

alter table voyage_todos enable row level security;
-- Politique créée seulement si absente (rejouable sans erreur, sans rien supprimer).
do $$ begin
  if not exists (select 1 from pg_policies where tablename = 'voyage_todos' and policyname = 'voyage_todos_rw') then
    create policy voyage_todos_rw on voyage_todos for all using (est_membre()) with check (est_membre());
  end if;
end $$;
